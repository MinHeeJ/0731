COMMENT ON COLUMN menu.status IS 'ACTIVE:활성|INACTIVE:비활성';

CREATE TABLE IF NOT EXISTS menu_permission (
  permission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_type varchar(20) NOT NULL,
  target_id varchar(60) NOT NULL,
  menu_id varchar(40) NOT NULL REFERENCES menu(menu_id),
  can_read char(1) NOT NULL DEFAULT 'N' CHECK (can_read IN ('Y','N')),
  can_create char(1) NOT NULL DEFAULT 'N' CHECK (can_create IN ('Y','N')),
  can_update char(1) NOT NULL DEFAULT 'N' CHECK (can_update IN ('Y','N')),
  can_disable char(1) NOT NULL DEFAULT 'N' CHECK (can_disable IN ('Y','N')),
  can_access char(1) NOT NULL DEFAULT 'N' CHECK (can_access IN ('Y','N')),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_menu_permission_target UNIQUE (target_type, target_id, menu_id)
);
COMMENT ON TABLE menu_permission IS '역할·조직·사용자별 메뉴 접근과 기능 권한을 서버와 화면에 동일하게 제공한다.';
COMMENT ON COLUMN menu_permission.target_type IS 'ROLE:역할|ORG:조직|USER:사용자';
COMMENT ON COLUMN menu_permission.can_read IS 'Y:허용|N:차단';
COMMENT ON COLUMN menu_permission.can_create IS 'Y:허용|N:차단';
COMMENT ON COLUMN menu_permission.can_update IS 'Y:허용|N:차단';
COMMENT ON COLUMN menu_permission.can_disable IS 'Y:허용|N:차단';
COMMENT ON COLUMN menu_permission.can_access IS 'Y:허용|N:차단';

