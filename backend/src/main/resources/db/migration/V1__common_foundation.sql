CREATE TABLE IF NOT EXISTS role (
  role_code varchar(3) PRIMARY KEY,
  role_name varchar(100) NOT NULL,
  purpose text NOT NULL,
  grant_criteria text NOT NULL,
  default_data_scope varchar(50) NOT NULL,
  use_yn char(1) NOT NULL DEFAULT 'Y' CHECK (use_yn IN ('Y','N')),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE role IS '교수업적평가시스템 공통기능에서 사용하는 업무 역할 기준정보.';
COMMENT ON COLUMN role.use_yn IS 'Y:사용|N:미사용';

CREATE TABLE IF NOT EXISTS organization (
  org_code varchar(20) PRIMARY KEY,
  org_name varchar(150) NOT NULL,
  org_type varchar(30) NOT NULL,
  parent_org_code varchar(20),
  start_date date NOT NULL,
  end_date date,
  status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  changed_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_organization_parent FOREIGN KEY (parent_org_code) REFERENCES organization(org_code)
);
COMMENT ON TABLE organization IS 'KORUS Mock 조직 스냅샷과 로컬 상하위 관계 적용기간을 관리한다.';
COMMENT ON COLUMN organization.status IS 'ACTIVE:활성|INACTIVE:비활성';


CREATE TABLE IF NOT EXISTS korus_personnel_snapshot (
  employee_no varchar(30) PRIMARY KEY,
  person_name varchar(100) NOT NULL,
  org_code varchar(20) NOT NULL,
  org_name varchar(150) NOT NULL,
  position_name varchar(100),
  duty_name varchar(100),
  employment_status varchar(20) NOT NULL,
  retirement_date date,
  last_synced_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  snapshot_status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  source_system varchar(30) NOT NULL DEFAULT 'KORUS_MOCK',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE korus_personnel_snapshot IS 'KORUS 원천 인사 정보를 로컬 실행용 Mock snapshot으로 보관하며 조회 전용으로만 사용한다.';
COMMENT ON COLUMN korus_personnel_snapshot.org_code IS 'organization.org_code 참조 의도 (Mock 원천 스냅샷이므로 FK 미선언)';
COMMENT ON COLUMN korus_personnel_snapshot.employment_status IS 'ACTIVE:재직|RETIRED:퇴직|LEAVE:휴직';
COMMENT ON COLUMN korus_personnel_snapshot.snapshot_status IS 'ACTIVE:최신|STALE:만료|DELETED:원천삭제';
COMMENT ON COLUMN korus_personnel_snapshot.source_system IS 'KORUS_MOCK:로컬Mock';


CREATE TABLE IF NOT EXISTS user_account (
  user_id varchar(30) PRIMARY KEY,
  login_id varchar(60) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  employee_no varchar(30) NOT NULL UNIQUE,
  user_name varchar(100) NOT NULL,
  org_code varchar(20) REFERENCES organization(org_code),
  org_name varchar(150) NOT NULL,
  position_name varchar(100),
  duty_name varchar(100),
  employment_status varchar(20) NOT NULL,
  retirement_date date,
  last_synced_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  system_use_yn char(1) NOT NULL DEFAULT 'Y' CHECK (system_use_yn IN ('Y','N')),
  korus_source_yn char(1) NOT NULL DEFAULT 'Y' CHECK (korus_source_yn IN ('Y','N')),
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
