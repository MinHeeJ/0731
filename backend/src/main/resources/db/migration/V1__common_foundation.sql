CREATE TABLE IF NOT EXISTS menu (
  menu_id varchar(40) PRIMARY KEY,
  parent_menu_id varchar(40),
  menu_name varchar(120) NOT NULL,
  screen_id varchar(40),
  route_path varchar(200),
  icon_name varchar(60),
  business_area varchar(60) NOT NULL,
  description text,
  sort_order integer NOT NULL DEFAULT 0,
  use_yn char(1) NOT NULL DEFAULT 'Y' CHECK (use_yn IN ('Y','N')),
  status varchar(20) NOT NULL DEFAULT 'ACTIVE',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_menu_parent FOREIGN KEY (parent_menu_id) REFERENCES menu(menu_id)
